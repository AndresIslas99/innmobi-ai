// innmobi.ai · home: the scroll story (six scenes as a canvas frame sequence) and the animated ledger.
//
// Progressive enhancement: the HTML is already the finished static page (posters + copy). This module upgrades it
// to scenes that advance with native scroll (no scroll-jacking, no wheel interception, no snap) only when it is
// safe: no reduced-motion, no Save-Data, no 2G/3G, canvas + createImageBitmap available and the first 24 frames of
// scene 1 arrive within 6 s. Otherwise it quietly stays static.
//
// Frames live in /assets/story/<version>/<scene>/{d,m}/NNNN.webp (d = desktop 1280x720, m = mobile).
// manifest.json is generated by scripts/story/make_manifest.mjs.

const MANIFEST_URL = '/assets/story/manifest.json';
const FIRST_FRAMES = 24;       // scene 1 frames that must arrive before going live (about 2 s of motion)
const GATE_MS = 6000;          // ...within this time, or we stay static
const MAX_PARALLEL = 6;        // simultaneous frame requests
const MAX_BG_PARALLEL = 4;     // of those, how many may be background (non-visible) downloads
const MIN_DOWNLINK = 8;        // Mbps (navigator.connection.downlink): below this the story stays static
const DISSOLVE_FROM = 0.94;    // last 6% of a scene dips through black into the first frame of the next (no two faces overlap)
const DAMPING = 9;             // playhead easing (higher = snappier)

const mqMobile = window.matchMedia('(max-width: 800px)');
const mqReduce = window.matchMedia('(prefers-reduced-motion: reduce)');

const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));
const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
const track = (name) => { try { if (typeof window.plausible === 'function') window.plausible(name); } catch (e) { /* analytics must never break the page */ } };
const setMode = (root, mode) => { root.dataset.mode = mode; };

/* ------------------------------------------------------------------ shared: header state, analytics, ledger */

function initPage(root) {
  const header = $('.site-header');
  const heightPx = () => (header ? header.offsetHeight : 85);
  const applyHeader = () => root.style.setProperty('--header-h', heightPx() + 'px');
  applyHeader();

  // Dark glass header while the story is on screen (works in static mode too).
  let ticking = false;
  const update = () => {
    ticking = false;
    const r = root.getBoundingClientRect();
    document.body.classList.toggle('story-on', r.bottom > heightPx() + 1);
  };
  const onScroll = () => { if (!ticking) { ticking = true; requestAnimationFrame(update); } };
  window.addEventListener('scroll', onScroll, { passive: true });
  window.addEventListener('resize', () => { applyHeader(); onScroll(); }, { passive: true });
  update();

  document.addEventListener('click', (e) => {
    const el = e.target.closest && e.target.closest('[data-story-evt]');
    if (el) track(el.dataset.storyEvt);
  });
}

function initLedger() {
  const ol = $('[data-ledger]');
  if (!ol || mqReduce.matches || !('IntersectionObserver' in window)) return;
  const rows = $$('.ledger-row', ol);
  ol.classList.add('ledger--js');

  const typeInto = (el) => {
    const full = el.textContent;
    el.textContent = '';
    let i = 0;
    const iv = setInterval(() => {
      el.textContent = full.slice(0, ++i);
      if (i >= full.length) clearInterval(iv);
    }, 55);
  };
  const reveal = (row, delay) => {
    row.style.transitionDelay = delay + 'ms';
    row.classList.add('is-in');
    const ts = $('.ts', row);
    if (ts) setTimeout(() => typeInto(ts), delay + 280);
  };

  let near = false;
  let lp = 0;
  let ticking = false;
  const update = () => {
    ticking = false;
    if (!near) return;
    const vh = window.innerHeight;
    const rect = ol.getBoundingClientRect();
    const reach = vh * 0.7 - rect.top; // px of the list the "reading line" has passed
    const lastDot = rows[rows.length - 1].offsetTop + 12; // the line is complete when it reaches the last row
    const p = clamp(reach / Math.max(1, lastDot), 0, 1);
    if (p > lp) { lp = p; ol.style.setProperty('--lp', lp.toFixed(4)); } // never rewinds
    let stagger = 0;
    rows.forEach((row) => {
      if (!row.classList.contains('is-in') && reach >= row.offsetTop + 8) { reveal(row, stagger); stagger += 120; }
    });
  };
  const schedule = () => { if (!ticking) { ticking = true; requestAnimationFrame(update); } };

  ol.style.setProperty('--lp', '0');
  new IntersectionObserver((entries) => {
    near = entries.some((e) => e.isIntersecting);
    if (near) schedule();
  }, { rootMargin: '0px 0px 20% 0px' }).observe(ol);
  window.addEventListener('scroll', schedule, { passive: true });
  window.addEventListener('resize', schedule, { passive: true });
  schedule();
}

/* ------------------------------------------------------------------ live engine */

function canGoLive() {
  if (mqReduce.matches) return 'reduced-motion';
  const c = navigator.connection || {};
  if (c.saveData) return 'save-data';
  if (['slow-2g', '2g', '3g'].includes(c.effectiveType)) return 'slow-connection';
  if (typeof c.downlink === 'number' && c.downlink > 0 && c.downlink < MIN_DOWNLINK) return 'slow-connection';
  if (navigator.deviceMemory && navigator.deviceMemory <= 2) return 'low-memory';
  const cv = document.createElement('canvas');
  if (!(cv.getContext && cv.getContext('2d')) || !window.createImageBitmap || !window.fetch) return 'no-canvas';
  return '';
}

async function startLive(root) {
  const stage = $('.story-stage', root);
  const canvas = $('.story-canvas', root);
  const layer = $('.story-copy-layer', root);
  const heroEl = $('.story-hero', root);
  const rail = $('.story-rail', root);
  const articles = $$('.story-scene', root);
  const header = $('.site-header');
  if (!stage || !canvas || !layer || !articles.length) return setMode(root, 'static:markup');

  let manifest;
  try {
    const res = await fetch(MANIFEST_URL);
    if (!res.ok) throw new Error('manifest ' + res.status);
    manifest = await res.json();
  } catch (e) {
    console.warn('[story] manifest unavailable, staying static');
    return setMode(root, 'static:manifest');
  }
  if (!manifest.scenes || manifest.scenes.length !== articles.length) return setMode(root, 'static:manifest');

  const N = manifest.scenes.length;
  const ctx = canvas.getContext('2d', { alpha: false });

  /* ---- frame pool (one variant at a time: phones get /m, everything else /d) ---- */
  let gen = 0;
  let variant = mqMobile.matches ? 'm' : 'd';
  let scenes = [];
  let inflight = 0;
  let inflightBg = 0;
  let decodedCount = 0;
  const posterUrls = articles.map((a) => { const img = $('.story-fig img', a); return img ? img.getAttribute('src') : null; });

  const decodeCap = () => (variant === 'm' ? 36 : 48);
  const frameUrl = (sc, j) => sc.base + String(j + 1).padStart(4, '0') + '.webp';

  function buildPool() {
    gen++;
    scenes.forEach((sc) => sc.bmps.forEach((b) => b && b.close && b.close()));
    decodedCount = 0;
    scenes = manifest.scenes.map((m, i) => {
      const spec = m[variant];
      return {
        i, id: m.id, n: m.frames, spec, snap: (m.fps || 12) <= 10, // 10 fps sources: show whole frames (blending them smears faces)
        base: manifest.base + m.id + '/' + spec.dir + '/',
        state: new Uint8Array(m.frames),      // 0 idle, 1 loading, 2 blob ready, 3 failed
        blobs: new Array(m.frames).fill(null),
        bmps: new Array(m.frames).fill(null),
        decoding: new Set(),
        fails: 0, dead: false, scan: 0, poster: null,
      };
    });
  }

  function fetchFrame(sc, j, hi) {
    const g = gen;
    sc.state[j] = 1;
    inflight++;
    if (!hi) inflightBg++;
    return fetch(frameUrl(sc, j), hi ? { priority: 'high' } : { priority: 'low' })
      .then((r) => { if (!r.ok) throw new Error('http ' + r.status); return r.blob(); })
      .then((blob) => {
        if (g !== gen) return;
        sc.blobs[j] = blob; sc.state[j] = 2; sc.fails = 0;
        if (wantSet.has(sc.i * 100000 + j)) decode(sc, j);
      })
      .catch(() => {
        if (g !== gen) return;
        sc.state[j] = 3; sc.fails++;
        if (sc.fails >= 3 && !sc.dead) {
          sc.dead = true;
          console.warn('[story] scene "' + sc.id + '" frames failed to load; showing its poster');
          loadPoster(sc);
        }
      })
      .finally(() => { inflight--; if (!hi) inflightBg--; if (g === gen) pump(); });
  }

  function loadPoster(sc) {
    const url = posterUrls[sc.i];
    if (!url) return;
    fetch(url).then((r) => r.blob()).then((b) => createImageBitmap(b)).then((bmp) => { sc.poster = bmp; needRender = true; schedule(); }).catch(() => {});
  }

  function decode(sc, j) {
    if (sc.bmps[j] || sc.decoding.has(j) || sc.state[j] !== 2) return;
    const g = gen;
    sc.decoding.add(j);
    createImageBitmap(sc.blobs[j]).then((b) => {
      sc.decoding.delete(j);
      if (g !== gen) { b.close(); return; }
      sc.bmps[j] = b; decodedCount++;
      if (decodedCount > decodeCap()) evict();
      needRender = true; schedule();
    }).catch(() => { sc.decoding.delete(j); sc.state[j] = 3; });
  }

  // Keep the decoded window small: drop the decoded bitmap farthest from the playhead (the blob stays; it re-decodes on demand).
  function evict() {
    let worst = null, worstD = -1;
    for (const sc of scenes) {
      for (let j = 0; j < sc.n; j++) {
        if (!sc.bmps[j] || wantSet.has(sc.i * 100000 + j)) continue;
        const d = Math.abs(sc.i + j / (sc.n - 1) - cur);
        if (d > worstD) { worstD = d; worst = [sc, j]; }
      }
    }
    if (worst) { worst[0].bmps[worst[1]].close(); worst[0].bmps[worst[1]] = null; decodedCount--; }
  }

  /* ---- what the playhead needs right now, and what to download next ---- */
  let wantList = [];
  let wantSet = new Set();
  let cur = 0, target = 0, lastDir = 1;
  let curScene = 0;
  let inView = true;
  let needRender = true;
  let userScrolled = false;
  let bgAllowed = false; // background downloads (frames the playhead does not need yet) wait for the first scroll, or 4 s

  function pos(g) { const s = Math.min(N - 1, Math.floor(g)); return { s, t: g - s }; }

  function computeWant() {
    const { s, t } = pos(cur);
    const sc = scenes[s];
    const c = Math.round(t * (sc.n - 1));
    const ahead = lastDir >= 0 ? 16 : 8, behind = lastDir >= 0 ? 8 : 16;
    const list = [];
    const add = (scene, j) => { if (j >= 0 && j < scene.n) list.push([scene, j]); };
    for (let k = 0; k <= Math.max(ahead, behind); k++) {
      if (k <= ahead) add(sc, c + k);
      if (k > 0 && k <= behind) add(sc, c - k);
    }
    if (t > 0.88 && s < N - 1) for (let k = 0; k < 6; k++) add(scenes[s + 1], k);
    if (t < 0.1 && s > 0) { const p = scenes[s - 1]; for (let k = 1; k <= 6; k++) add(p, p.n - k); }
    wantList = list;
    wantSet = new Set(list.map(([x, j]) => x.i * 100000 + j));
    curScene = s;
    for (const [x, j] of list) decode(x, j);
  }

  function nextJob() {
    for (const [sc, j] of wantList) if (sc.state[j] === 0 && !sc.dead) return { sc, j, hi: true };
    if (!bgAllowed || inflightBg >= MAX_BG_PARALLEL) return null;
    const { t } = pos(cur);
    // Idle page: only scene 1 (the next one once the playhead is well into it). Once the person scrolls: up to two scenes ahead.
    const ahead = userScrolled ? (t > 0.1 ? 2 : 1) : (t > 0.25 ? 1 : 0);
    const lastAllowed = Math.min(N - 1, curScene + ahead);
    for (let i = curScene; i <= lastAllowed; i++) {
      const sc = scenes[i];
      if (sc.dead) continue;
      while (sc.scan < sc.n && sc.state[sc.scan] !== 0) sc.scan++;
      if (sc.scan < sc.n) return { sc, j: sc.scan, hi: false };
    }
    return null;
  }

  function pump() {
    if (!inView) return;
    while (inflight < MAX_PARALLEL) {
      const job = nextJob();
      if (!job) break;
      fetchFrame(job.sc, job.j, job.hi);
    }
  }

  /* ---- drawing ---- */
  let cw = 0, ch = 0;
  function sizeCanvas() {
    const r = canvas.getBoundingClientRect();
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    let w = Math.round(r.width * dpr), h = Math.round(r.height * dpr);
    if (w > 1920) { h = Math.round((h * 1920) / w); w = 1920; }
    if (w < 2 || h < 2) return;
    if (canvas.width !== w || canvas.height !== h) { canvas.width = w; canvas.height = h; needRender = true; }
    cw = w; ch = h;
  }

  function nearest(sc, j) {
    if (sc.dead && sc.poster) return sc.poster;
    for (let d = 0; d < 60; d++) {
      const a = sc.bmps[j - d]; if (a) return a;
      const b = sc.bmps[j + d]; if (b) return b;
    }
    return sc.poster || null;
  }

  function collect(sc, f, alpha, out) {
    const lo = clamp(Math.floor(f), 0, sc.n - 1);
    const hi = Math.min(lo + 1, sc.n - 1);
    const frac = sc.snap ? (f - lo >= 0.5 ? 1 : 0) : f - lo;
    const a = nearest(sc, frac === 1 && hi !== lo ? hi : lo);
    if (!a) return;
    out.push({ b: a, a: alpha, sc });
    if (!sc.snap && frac > 0.04 && hi !== lo) {
      const b = nearest(sc, hi);
      if (b && b !== a) out.push({ b, a: alpha * frac, sc });
    }
  }

  // Letterboxed (contain) scenes: fill the empty bands with a dim, heavily blurred copy of the frame. The blur is free:
  // the frame is drawn onto a tiny canvas and stretched back up.
  const ambient = document.createElement('canvas');
  ambient.width = 24; ambient.height = 30;
  const actx = ambient.getContext('2d');
  function drawAmbient(bmp, alpha) {
    const sc = Math.max(ambient.width / bmp.width, ambient.height / bmp.height);
    const dw = bmp.width * sc, dh = bmp.height * sc;
    actx.drawImage(bmp, (ambient.width - dw) / 2, (ambient.height - dh) / 2, dw, dh);
    ctx.globalAlpha = alpha * 0.5;
    ctx.imageSmoothingEnabled = true;
    ctx.drawImage(ambient, 0, 0, cw, ch);
  }

  function drawBitmap(bmp, spec, alpha) {
    const iw = bmp.width, ih = bmp.height;
    if (spec.fit === 'contain' && cw / ch < iw / ih) drawAmbient(bmp, alpha);
    const sc = spec.fit === 'contain' ? Math.min(cw / iw, ch / ih) : Math.max(cw / iw, ch / ih);
    const dw = iw * sc, dh = ih * sc;
    let dx = cw / 2 - (spec.focal || 0.5) * dw;
    dx = dw <= cw ? (cw - dw) / 2 : clamp(dx, cw - dw, 0);
    const dy = (ch - dh) / 2;
    ctx.globalAlpha = alpha;
    ctx.drawImage(bmp, dx, dy, dw, dh);
  }

  let painted = false;
  function render() {
    if (!cw) return;
    const { s, t } = pos(cur);
    const sc = scenes[s];
    const draws = [];
    // Scene changes dip through black: the outgoing scene fades out over the first half of the window, the next one
    // fades in over the second half, so two faces are never on screen at once.
    const u = t > DISSOLVE_FROM && s < N - 1 ? (t - DISSOLVE_FROM) / (1 - DISSOLVE_FROM) : 0;
    const ease = (x) => { x = clamp(x, 0, 1); return x * x * (3 - 2 * x); };
    collect(sc, t * (sc.n - 1), 1 - ease(u * 2), draws);
    if (u > 0.5) collect(scenes[s + 1], 0, ease(u * 2 - 1), draws);
    if (!draws.length) return; // keep whatever is on the canvas (never a blank frame)
    ctx.globalAlpha = 1;
    ctx.fillStyle = '#0F0F10';
    ctx.fillRect(0, 0, cw, ch);
    for (const d of draws) drawBitmap(d.b, d.sc.spec, d.a);
    ctx.globalAlpha = 1;
    if (!painted) { painted = true; root.classList.add('story--painted'); }
  }

  /* ---- copy, rail and stage variables ---- */
  const lastP = articles.map(() => -1);
  let lastHero = -1, lastEnd = -1, lastActive = -1, maxScene = -1;
  const ramp = (x) => clamp(x, 0, 1);

  function applyVars() {
    const { s, t } = pos(cur);
    const heroOut = s === 0 ? ramp((t - 0.12) / 0.14) : 1;
    if (Math.abs(heroOut - lastHero) > 0.004 || heroOut === 0 || heroOut === 1) {
      stage.style.setProperty('--hero-out', heroOut.toFixed(3));
      heroEl.classList.toggle('is-off', heroOut > 0.95);
      lastHero = heroOut;
    }
    const end = s === N - 1 ? ramp((t - 0.9) / 0.1) : 0;
    if (Math.abs(end - lastEnd) > 0.004 || end === 0 || end === 1) { stage.style.setProperty('--end', end.toFixed(3)); lastEnd = end; }
    articles.forEach((a, i) => {
      const p = i < s ? 1 : i > s ? 0 : t;
      if (Math.abs(p - lastP[i]) > 0.0015 || p === 0 || p === 1) {
        a.style.setProperty('--p', p.toFixed(4));
        lastP[i] = p;
        const inn = ramp((p - (i === 0 ? 0.26 : 0.12)) / (i === 0 ? 0.14 : 0.16));
        const out = i === N - 1 ? 0 : ramp((p - 0.82) / 0.12);
        a.classList.toggle('is-off', inn * (1 - out) < 0.3);
      }
    });
    if (s !== lastActive) {
      lastActive = s;
      $$('a[data-i]', rail).forEach((a) => (+a.dataset.i === s ? a.setAttribute('aria-current', 'step') : a.removeAttribute('aria-current')));
    }
    if (s > maxScene) { for (let k = maxScene + 1; k <= s; k++) track('story_scene_' + (k + 1)); maxScene = s; }
  }

  /* ---- scroll metrics and the rAF loop ---- */
  let secTop = 0, range = 1, headerH = 85;
  function measure() {
    headerH = header ? header.offsetHeight : 85;
    root.style.setProperty('--header-h', headerH + 'px');
    secTop = root.getBoundingClientRect().top + window.scrollY;
    range = Math.max(1, root.offsetHeight - stage.offsetHeight);
    sizeCanvas();
  }
  const targetG = () => clamp((window.scrollY + headerH - secTop) / range, 0, 1) * N;

  let raf = 0, last = 0, hidden = document.hidden;
  function schedule() {
    if (raf || hidden || !inView) return;
    last = performance.now();
    raf = requestAnimationFrame(tick);
  }
  function tick(now) {
    raf = 0;
    const dt = Math.min(0.1, Math.max(0.001, (now - last) / 1000));
    last = now;
    const newTarget = targetG();
    if (Math.abs(newTarget - target) > 1e-6) lastDir = newTarget >= target ? 1 : -1;
    target = newTarget;
    const diff = target - cur;
    const eps = 0.02 / 96; // in scenes: a fiftieth of a frame
    const moving = Math.abs(diff) > eps;
    cur = moving ? cur + diff * (1 - Math.exp(-dt * DAMPING)) : target;
    if (moving || needRender || wantList.length === 0) {
      computeWant();
      applyVars();
      render();
      needRender = false;
      pump();
    }
    if (moving) schedule(); // stops entirely when settled: zero idle CPU
  }

  /* ---- rail + skip ---- */
  function goScene(i) {
    const g = i + 0.55; // lands with the scene copy fully visible
    window.scrollTo({ top: secTop - headerH + (g / N) * range, behavior: 'smooth' });
  }
  rail.addEventListener('click', (e) => {
    const a = e.target.closest('a[data-i]');
    if (!a) return;
    e.preventDefault();
    goScene(+a.dataset.i);
  });

  /* ---- gate: first frames of scene 1 must arrive in time ---- */
  buildPool();
  try {
    const sc0 = scenes[0];
    const count = Math.min(FIRST_FRAMES, sc0.n);
    let next = 0;
    const worker = async () => { while (next < count) { const j = next++; await fetchFrame(sc0, j, true); } };
    await Promise.race([
      Promise.all(Array.from({ length: MAX_PARALLEL }, worker)),
      new Promise((_, rej) => setTimeout(() => rej(new Error('slow')), GATE_MS)),
    ]);
    for (let j = 0; j < count; j++) if (sc0.state[j] !== 2) throw new Error('missing');
  } catch (e) {
    gen++; // abandon in-flight work
    console.warn('[story] first frames did not arrive in time; staying static');
    return setMode(root, 'static:slow');
  }

  // The user may have scrolled while we were loading. Mid-story in the static layout: stay static.
  // Past the story (e.g. back-navigation restoring scroll): keep their place relative to the ledger.
  const reg = $('#registro');
  const sy = window.scrollY;
  const regBefore = reg ? reg.getBoundingClientRect().top + sy : Infinity;
  if (sy > 40 && sy < regBefore - 10) return setMode(root, 'static:scrolled');

  // Go live: move the copy into the stage, drop the static figures, switch the layout.
  articles.forEach((a) => { const fig = $('.story-fig', a); if (fig) fig.remove(); layer.append(a); });
  root.classList.add('story--live');
  setMode(root, 'live');
  measure();
  if (reg && sy >= regBefore - 10) {
    const regAfter = reg.getBoundingClientRect().top + window.scrollY;
    window.scrollTo({ top: regAfter + (sy - regBefore), behavior: 'instant' });
  }
  target = cur = targetG();
  computeWant();
  applyVars();
  render();
  schedule();

  /* ---- listeners ---- */
  window.addEventListener('scroll', () => {
    if (!userScrolled) { userScrolled = true; bgAllowed = true; pump(); }
    if (!raf) schedule();
  }, { passive: true });
  setTimeout(() => { bgAllowed = true; pump(); }, 4000);
  let resizeRaf = 0;
  const onResize = () => {
    if (resizeRaf) return;
    resizeRaf = requestAnimationFrame(() => { resizeRaf = 0; measure(); needRender = true; schedule(); });
  };
  window.addEventListener('resize', onResize, { passive: true });
  window.addEventListener('load', onResize);
  if ('ResizeObserver' in window) new ResizeObserver(onResize).observe(stage);
  document.addEventListener('visibilitychange', () => { hidden = document.hidden; if (!hidden) { needRender = true; schedule(); } });
  new IntersectionObserver((entries) => {
    inView = entries.some((e) => e.isIntersecting);
    if (inView) { measure(); needRender = true; schedule(); pump(); }
  }, { rootMargin: '100% 0px 100% 0px' }).observe(root);
  mqMobile.addEventListener('change', () => {
    variant = mqMobile.matches ? 'm' : 'd';
    buildPool(); // other frame set: start over from what the playhead needs
    sizeCanvas();
    wantList = [];
    needRender = true;
    computeWant();
    pump();
    schedule();
  });

  pump(); // background-load the rest of scene 1
}

/* ------------------------------------------------------------------ boot */

function boot() {
  const root = $('[data-story]');
  if (!root) return;
  setMode(root, 'static');
  initPage(root);
  initLedger();

  const reason = canGoLive();
  if (reason) { setMode(root, 'static:' + reason); }
  else { startLive(root).catch((e) => { console.warn('[story] staying static:', e && e.message); setMode(root, 'static:error'); }); }

  // If the person changes the motion preference while the page is open, re-evaluate cleanly.
  mqReduce.addEventListener('change', () => location.reload());
}

if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
else boot();
